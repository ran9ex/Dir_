"""
Dir' (درع): DPIA-style report generator (Arabic, Markdown).

Built only from the audit statistics, so it contains numbers and categories, never personal data.

On legal references: this prototype deliberately does NOT print PDPL article numbers. They were not
verified against the official text. Penalty ranges below come from public legal summaries
(DLA Piper, Latham & Watkins) and must be confirmed with a qualified adviser before use.
"""
from __future__ import annotations

from datetime import date

from detectors import TYPE_INFO
from risk import level_of

_CAT_AR = {"identifier": "معرّف شخصي", "financial": "مالي", "contact": "تواصل", "name": "اسم", "sensitive_health": "صحي (حساس)"}


def _table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def generate_report(stats: dict, org: str = "الجهة (اسم تجريبي)", period: str = "الفترة التجريبية",
                    rules_ar: dict | None = None) -> str:
    n = stats["requests"]
    if n == 0:
        return "# تقرير تقييم الأثر على الخصوصية\n\nلا توجد طلبات مسجلة بعد. شغّل بعض السيناريوهات ثم أعد توليد التقرير."

    inh_k, inh_ar = level_of(stats["avg_inherent"])
    res_k, res_ar = level_of(stats["avg_residual"])
    reduction = 0 if stats["avg_inherent"] == 0 else round(100 * (1 - stats["avg_residual"] / stats["avg_inherent"]))

    L = []
    L.append("# تقرير تقييم الأثر على الخصوصية (مبسّط)")
    L.append("**موضوع التقييم:** استخدام الموظفين لأدوات الذكاء الاصطناعي التوليدي عبر بوابة «درع»")
    L.append(f"**الجهة:** {org} · **الفترة:** {period} · **تاريخ التوليد:** {date.today().isoformat()}")
    L.append("> هذا التقرير مولَّد آلياً من سجل التدقيق لنموذج أولي، وبيانات العرض كلها اصطناعية. ليس استشارة قانونية.")

    L.append("## 1. الملخص التنفيذي")
    L.append(_table(["المؤشر", "القيمة"], [
        ["عدد الطلبات المعالجة", n],
        ["طلبات أُوقفت قبل وصولها للنموذج", stats["blocked"]],
        ["طلبات مسموحة مع تحذير", stats["with_warnings"]],
        ["طلبات مسموحة (مع حجب البيانات الحساسة عند وجودها)", stats["clean"]],
        ["مستندات عُزلت لاحتوائها تعليمات خفية", stats["docs_quarantined"]],
        ["عناصر بيانات شخصية استُبدلت برموز قبل الإرسال", stats["items_masked"]],
        ["متوسط المخاطر قبل الضوابط", f"{stats['avg_inherent']} / 100 ({inh_ar})"],
        ["متوسط المخاطر بعد الضوابط", f"{stats['avg_residual']} / 100 ({res_ar})"],
        ["انخفاض المخاطر بعد الضوابط", f"{reduction}%"],
        ["متوسط زمن المعالجة", f"{stats['avg_latency_ms']} م.ث (بدون زمن النموذج)"],
    ]))

    L.append("## 2. وصف المعالجة")
    L.append("يرسل الموظفون نصوصاً ومستندات إلى نموذج ذكاء اصطناعي خارجي. تعترض «درع» الطلب قبل خروجه من الجهة، "
             "فتفحص النص والمستندات بحثاً عن بيانات شخصية وهجمات حقن التعليمات، وتستبدل البيانات الحساسة برموز قابلة للإرجاع، "
             "ولا يصل إلى النموذج إلا النص المحجوب. تُفحص ردود النموذج قبل عرضها، ثم تُعاد القيم الأصلية للموظف داخل الجهة فقط.")

    L.append("## 3. البيانات الشخصية المرصودة")
    rows = []
    for t, c in sorted(stats["data_types"].items(), key=lambda x: -x[1]):
        info = TYPE_INFO[t]
        rows.append([info["label_ar"], _CAT_AR.get(info["category"], info["category"]), c,
                     "نعم (استبدال برمز)" if info["mask"] else "لا (تنبيه وزيادة تقدير المخاطر)"])
    L.append(_table(["نوع البيانات", "الفئة", "عدد المرات", "يُحجب قبل الإرسال؟"], rows) if rows else "لم تُرصد بيانات شخصية.")
    L.append("البيانات الصحية تُعد حساسة في الأنظمة المقارنة، ولذلك رُفعت درجة المخاطر عند اقترانها بمعرّف شخصي.")

    L.append("## 4. التهديدات المرصودة")
    arows = []
    for rid, c in sorted(stats["attack_rules"].items(), key=lambda x: -x[1]):
        fam = (rules_ar or {}).get(rid, rid)
        arows.append([fam, rid, c])
    L.append(_table(["نوع الهجوم", "المعرّف", "عدد المرات"], arows) if arows else "لم تُرصد هجمات.")
    if stats["owasp"]:
        L.append("**تصنيف OWASP Top 10 for LLM Applications:** " + "، ".join(f"{k} ({v})" for k, v in sorted(stats["owasp"].items())))
    if stats["output_events"]:
        names = {"exfil_image": "صورة قد تسرّب البيانات", "exfil_link": "رابط قد يسرّب البيانات",
                 "system_prompt_leak": "تسريب تعليمات النظام", "secret_leak": "تسريب مفتاح أو سر",
                 "pii_in_output": "بيانات شخصية خام في رد النموذج"}
        L.append("**ما حجبه حارس المخرجات:** " + "، ".join(f"{names.get(k, k)} ({v})" for k, v in stats["output_events"].items()))

    L.append("## 5. تقييم المخاطر")
    L.append("درجة من 0 إلى 100 بمعادلة شفافة: وزن لكل نوع بيانات × عددها، مع زيادة عند اجتماع معرّف شخصي مع بيانات صحية أو اسم، "
             "وإضافة لقوة إشارة الهجوم ولوجهة النموذج الخارجي. تُحسب مرتين: قبل الضوابط وبعدها. الأوزان تقدير هندسي للنموذج الأولي وليست معياراً نظامياً.")
    L.append(_table(["", "المتوسط", "المستوى", "أعلى قيمة"], [
        ["قبل الضوابط (الكامن)", stats["avg_inherent"], inh_ar, stats["max_inherent"]],
        ["بعد الضوابط (المتبقي)", stats["avg_residual"], res_ar, "-"],
    ]))

    L.append("## 6. الضوابط المطبقة")
    L.append("\n".join([
        "- تطبيع النص العربي (الأرقام العربية الهندية، التشكيل، الحروف المخفية) قبل أي فحص.",
        "- كشف الهوية الوطنية والإقامة والآيبان والجوال والبطاقة بفحص المجموع الاختباري.",
        "- استبدال البيانات برموز قابلة للإرجاع، وخزنة منفصلة لكل جلسة بمدة صلاحية محددة.",
        "- كشف حقن التعليمات العربي والإنجليزي، ومباشراً وغير مباشر (داخل المستندات)، وعزل المستند المصاب.",
        "- حارس المخرجات: منع الصور والروابط المسرِّبة وتسريب تعليمات النظام والمفاتيح.",
        "- سجل تدقيق لا يحتوي نصوصاً ولا بيانات شخصية، بل أنواعاً وأعداداً ودرجات فقط.",
    ]))

    L.append("## 7. الربط بمتطلبات نظام حماية البيانات الشخصية")
    L.append(_table(["المبدأ / المتطلب", "ما يقدمه درع", "ملاحظة"], [
        ["تقليل البيانات والغرض من المعالجة", "لا يغادر الجهة إلا النص المحجوب", "تحديد الغرض المشروع مسؤولية الجهة"],
        ["الضمانات الأمنية للمعالجة", "كشف الهجمات، عزل المستندات، حارس المخرجات", "تكمّل ضوابط الهيئة الوطنية للأمن السيبراني ولا تغني عنها"],
        ["نقل البيانات خارج المملكة", "يقلل تعريض البيانات الشخصية للنموذج الخارجي", "الحكم النظامي على النقل قرار قانوني للجهة"],
        ["الإبلاغ عن التسرب", "سجل التدقيق يساعد على رصد الحوادث وتوقيتها", "تفيد مصادر قانونية بمهلة 72 ساعة لإبلاغ سدايا؛ يُتحقق منها"],
        ["حقوق أصحاب البيانات", "لا يخزن نصوص المستخدمين ولا قيمها", "الإجابة عن طلبات الأفراد تظل عند الجهة"],
    ]))
    L.append("**العقوبات (وفق ملخصات قانونية عامة، تُراجع قبل الاعتماد):** غرامة تصل إلى 5 ملايين ريال عن المخالفات العامة وتضاعف عند التكرار، "
             "وسجن حتى سنتين و/أو غرامة حتى 3 ملايين ريال عند الإفصاح عن بيانات حساسة بقصد الإضرار أو تحقيق منفعة شخصية. "
             "أرقام المواد لم تُدرج عمداً وتُضاف بعد مطابقتها مع النص الرسمي.")

    recs = []
    if stats["blocked"]:
        recs.append(f"راجعوا مصدر الطلبات الموقوفة ({stats['blocked']}) لتمييز الاختبار المتعمد من الاستخدام الخاطئ.")
    if stats["docs_quarantined"]:
        recs.append(f"افحصوا مصدر المستندات المعزولة ({stats['docs_quarantined']}) وأبلغوا مرسليها الموثوقين.")
    if stats["output_events"]:
        recs.append("ردود النموذج احتوت محتوى مسرِّباً: شدّدوا أذونات الأدوات والاتصال الخارجي للنموذج.")
    if "sensitive_health" in {TYPE_INFO[t]["category"] for t in stats["data_types"]}:
        recs.append("رُصدت بيانات صحية: قيّدوا استخدام النماذج الخارجية لهذه الفئة أو انقلوا المعالجة إلى بيئة داخل المملكة.")
    recs += ["درّبوا الموظفين على ما يُسمح بلصقه في أدوات الذكاء الاصطناعي.",
             "اعتمدوا قائمة بيضاء للنطاقات الموثوقة بدل منع كل الروابط.",
             "اعرضوا هذا التقرير على مسؤول حماية البيانات والمستشار القانوني قبل اعتماده."]
    L.append("## 8. التوصيات")
    L.append("\n".join(f"{i}. {r}" for i, r in enumerate(recs, 1)))

    L.append("## 9. حدود هذا التقرير")
    L.append("\n".join([
        "- كشف الأسماء استدلالي (كلمات مفتاحية وقائمة أسماء صغيرة) وقد يفوّت أسماء غير مألوفة.",
        "- كشف الهجمات قائم على قواعد: يغطي عائلات صياغات معروفة وليس الفهم الدلالي.",
        "- الخزنة في ذاكرة العملية وغير مشفّرة في النموذج الأولي.",
        "- بيانات العرض اصطناعية، والأرقام لا تمثل أداءً في بيئة حقيقية.",
    ]))
    return "\n\n".join(L)
