def _attacks(rng: random.Random, n: int) -> list:
    out = set()
    makers = [
        lambda: f"{rng.choice(IGNORE_AR)} {rng.choice(IGNORE_OBJ_AR)} {rng.choice(THEN_AR)} {rng.choice(EXTRACT_AR)} {rng.choice(EXTRACT_OBJ_AR)}",
        lambda: f"{rng.choice(IGNORE_AR)} {rng.choice(IGNORE_OBJ_AR)}",
        lambda: f"{rng.choice(EXTRACT_AR)} {rng.choice(EXTRACT_OBJ_AR)}",
        lambda: f"{rng.choice(ROLE_AR)} {rng.choice(THEN_AR)} {rng.choice(EXTRACT_AR)} {rng.choice(EXTRACT_OBJ_AR)}",
        lambda: rng.choice(ROLE_AR),
        lambda: f"{rng.choice(EXFIL_AR)} {rng.choice(URLS)}",
        lambda: f"{rng.choice(BULK_AR)} {rng.choice(THEN_AR)} {rng.choice(EXFIL_AR)} {rng.choice(URLS)}",
        lambda: rng.choice(BULK_AR),
        lambda: f"{rng.choice(IGNORE_EN)} {rng.choice(IGNORE_OBJ_EN)} and {rng.choice(EXTRACT_EN).lower()} {rng.choice(EXTRACT_OBJ_EN)}",
        lambda: f"{rng.choice(IGNORE_EN)} {rng.choice(IGNORE_OBJ_EN)}",
        lambda: f"{rng.choice(EXTRACT_EN)} {rng.choice(EXTRACT_OBJ_EN)}",
        lambda: rng.choice(ROLE_EN),
        lambda: f"{rng.choice(IGNORE_AR)} {rng.choice(IGNORE_OBJ_AR)} and {rng.choice(EXTRACT_EN).lower()} {rng.choice(EXTRACT_OBJ_EN)}",
    ]
    guard = 0
    while len(out) < n and guard < n * 40:
        guard += 1
        out.add(rng.choice(WRAPPERS).format(x=rng.choice(makers)()))
    return sorted(out)


def _benign(rng: random.Random, n: int) -> list:
    out = set(HARD_NEG) | set(CHAT)
    wrappers = ["{x}", "من فضلك {x}", "{x} لو سمحت", "{x} باختصار", "{x} في ثلاث نقاط", "ممكن {x}؟", "Please {y}"]
    guard = 0
    while len(out) < n and guard < n * 40:
        guard += 1
        x = f"{rng.choice(TASKS)} {rng.choice(TASK_OBJ)}"
        w = rng.choice(wrappers)
        out.add(w.format(x=x, y="summarize the attached report") if "{y}" in w else w.format(x=x))
        if rng.random() < 0.3:
            out.add(rng.choice(HARD_NEG) + " " + rng.choice(["", "شكراً", "ضروري اليوم"]).strip())
    return sorted(s.strip() for s in out)


def build(seed: int = 11, n_attack: int = 800, n_benign: int = 1500):
    rng = random.Random(seed)
    held_out = {normalize(a["text"]).text for a in ed.DEV_ATTACKS + ed.TEST_ATTACKS} | \
               {normalize(t).text for t in ed.DEV_BENIGN + ed.TEST_BENIGN + list(ed.DEV_HARD_NEGATIVES)}
    rows = [{"text": t, "label": 1} for t in _attacks(rng, n_attack)] + [{"text": t, "label": 0} for t in _benign(rng, n_benign)]
    rows = [r for r in rows if normalize(r["text"]).text not in held_out]
    rng.shuffle(rows)
    k = int(len(rows) * 0.9)
    return rows[:k], rows[k:]


